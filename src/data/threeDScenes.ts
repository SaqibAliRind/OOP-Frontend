export function getThreeDSceneConfig(sceneId: string): ThreeDSceneConfig | undefined {
  return threeDSceneConfigs.find(s => s.id === sceneId);
}

export function getSceneConfigsForModule(moduleId: string): ThreeDSceneConfig[] {
  return threeDSceneConfigs.filter(s => s.moduleId === moduleId);
}

export function getSceneConfigsForLesson(lessonId: string): ThreeDSceneConfig[] {
  return threeDSceneConfigs.filter(s => s.lessonIds.includes(lessonId));
}